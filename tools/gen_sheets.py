#!/usr/bin/env python3
"""Builds this port's art from the same drawing code as the 3DS game, at four times the size.

Outputs (all committed, so building the game only needs a C++ compiler):
  romfs/gfx/*.png               texture atlases and boards
  port/generated/*.h            sprite names and where each one sits

Requires Pillow and numpy. Output is deterministic.
"""
import os
import sys

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
import gen_assets as g  # noqa: E402
import gen_backgrounds as b  # noqa: E402

PAD = 4
BOARD_K = 3
OUT_GFX = os.path.join(ROOT, "romfs", "gfx")
OUT_H = os.path.join(ROOT, "port", "generated")
REAL_SHRINK = g.shrink


def fruit_list():
    out = []
    for spec in g.FRUITS:
        whole, left, right = g.fruit_images(spec)
        out += [(spec[0], whole), (spec[0] + "_l", left), (spec[0] + "_r", right)]
    return out + [("bomb", g.spr_bomb()), ("sunburst", g.spr_sunburst())]


def sprite_list():
    return [
        ("pw_freeze", g.spr_power("freeze")), ("pw_double", g.spr_power("double")), ("pw_frenzy", g.spr_power("frenzy")),
        ("splat0", g.spr_splat(1)), ("splat1", g.spr_splat(2)), ("splat2", g.spr_splat(3)),
        # The glow is stretched widely behind bombs, so a small one would show its square grid at HD sizes.
        ("drop", g.spr_drop()), ("spark", g.spr_spark()), ("glow", g.spr_soft(48 if g.shrink is REAL_SHRINK else 384)), ("ring", g.spr_ring()), ("crack", g.spr_crack()),
        ("pip_on", g.spr_pip(True)), ("pip_off", g.spr_pip(False)), ("panel", g.spr_panel()), ("plank", g.spr_plank()),
        ("plank_focus", g.spr_plank_focus()), ("knob", g.spr_knob()), ("arrow", g.spr_arrow()), ("arrow_back", g.spr_arrow(True)),
        ("post", g.spr_post()), ("ic_clock", g.spr_icon("clock")), ("ic_leaf", g.spr_icon("leaf")), ("ic_fast", g.spr_icon("fast")),
        ("ic_one", g.spr_icon("one")), ("ic_mine", g.spr_icon("mine")), ("ic_chain", g.spr_icon("chain")),
        ("coin", g.spr_coin()), ("coin_back", g.spr_coin(True)), ("coin_rim", g.spr_coin_rim()),
        ("pw_magnet", g.spr_power("magnet")), ("pw_wide", g.spr_power("wide")), ("pw_shield", g.spr_power("shield")), ("pw_time", g.spr_power("time")),
    ]


def logo_list():
    return [("logo", g.spr_logo())]


def font_list():
    return [(f"g{i:02d}", gl[1]) for i, gl in enumerate(g.font_glyphs())]


def pack(images, width):
    """Tallest first, on shelves. Returns where each image goes and the atlas height."""
    order = sorted(range(len(images)), key=lambda i: -images[i][1].height)
    spots = [None] * len(images)
    x = y = PAD
    shelf = 0
    for i in order:
        img = images[i][1]
        if x + img.width + PAD > width:
            x = PAD
            y += shelf + PAD
            shelf = 0
        spots[i] = (x, y)
        x += img.width + PAD
        shelf = max(shelf, img.height)
    return spots, y + shelf + PAD


def write_atlas(name, build, width, lines, defines=True):
    # The sizes the game's layout expects come from the 3DS drawing; the pixels from the big one.
    g.shrink = REAL_SHRINK
    small = build()
    g.shrink = lambda img: img
    images = build()
    width = max(width, max(img.width for _, img in images) + PAD * 2)
    spots, height = pack(images, width)
    atlas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    rects = []
    for (key, img), (x, y), (_, s) in zip(images, spots, small):
        atlas.paste(img.convert("RGBA"), (x, y))
        rects.append("{%d,%d,%d,%d,%d,%d}" % (x, y, img.width, img.height, s.width, s.height))
        ratio = img.width / s.width
        if ratio != g.SS:
            print(f"  note: {name}/{key} is {img.width}x{img.height} for {s.width}x{s.height}")
    atlas.save(os.path.join(OUT_GFX, name + ".png"), optimize=True)
    lines.append(f"static const SheetRect kRects{name.capitalize()}[] = {{" + ",".join(rects) + "};")
    if defines:
        with open(os.path.join(OUT_H, name + ".h"), "w", newline="\n") as f:
            f.write("// Generated by tools/gen_sheets.py. Do not edit.\n#pragma once\n")
            for i, (key, _) in enumerate(images):
                f.write(f"#define {name}_{key}_idx {i}\n")
    print(name, f"{width}x{height}", os.path.getsize(os.path.join(OUT_GFX, name + ".png")) // 1024, "KB")


def main():
    os.makedirs(OUT_GFX, exist_ok=True)
    os.makedirs(OUT_H, exist_ok=True)
    lines = ["// Generated by tools/gen_sheets.py. Do not edit.", "#pragma once", "struct SheetRect { float x, y, w, h, lw, lh; };"]
    write_atlas("fruit", fruit_list, 2048, lines)
    write_atlas("sprites", sprite_list, 2048, lines)
    write_atlas("logo", logo_list, 1024, lines)
    write_atlas("font", font_list, 2048, lines, defines=False)
    b.set_board_size(427, 240, BOARD_K)
    for i, board in enumerate(b.bg_boards()):
        p = os.path.join(OUT_GFX, f"board{i}.png")
        board.convert("RGB").save(p, optimize=True)
        print("board", i, board.size, os.path.getsize(p) // 1024, "KB")
    w, h = board.size
    lines.append("static const SheetRect kRectsBoard[] = {{0,0,%d,%d,427,240}};" % (w, h))
    with open(os.path.join(OUT_H, "sheet_rects.h"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
